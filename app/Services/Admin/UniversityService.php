                ]);
            if ($request->val == 1) {
                $response['message'] = 'University enabled successfully';
            } else {
                $response['message'] = 'University disabled successfully';
            }
            $response['error'] = null;
            $response['status'] = 200;
            return response()->json($response, $response['status']);
        } catch (\Exception $e) {
            return response()->json(['error' => $e->getMessage()], 400);
        }
    }

    public function store($request) {
        try {
            $university = $request['id'] ? University::firstOrNew(['id' => $request['id']]) : new University;
            $university->name = $request['name'];
            $university->save();
            $response['message'] = ($request['id']) ? 'University updated successfully.' : 'University added successfully.';
            $response['error'] = null;
            $response['status'] = 201;
            return response()->json($response, $response['status']);
        } catch (\Exception $e) {
            return response()->json(['error' => $e->getMessage()], 400);
        }
    }

    public function delete($request) {
        try {
            $id = $request->id;
            University::where('id', $id)->delete();
            $response['message'] = 'University deleted successfully.';
            $response['error'] = null;
            $response['status'] = 200;
            return response()->json($response, $response['status']);
        } catch (\Exception $e) {
            return response()->json(['error' => $e->getMessage()], 400);
        }
    }

}